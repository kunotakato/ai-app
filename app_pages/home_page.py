import streamlit as st


def render_home_page():
    """
    初めて使う人向けの案内ページです。
    6つの機能があっても迷わないように、使う順番を示します。
    """

    st.header("🚀 はじめに")
    st.caption("CareerCraft AIを初めて使う人向けのガイドです。")

    st.info(
        """
        CareerCraft AIは、転職活動を最初から最後までサポートするAIツールです。
        迷ったら、下の順番で進めてください。
        """
    )

    st.subheader("まずはこの順番で進めましょう")

    st.markdown(
        """
        ### ① キャリア地図
        今の状況・転職理由・不安・理想の働き方を整理します。  
        **最初にここから始めるのがおすすめです。**

        ### ② 自己分析・職種診断
        自分の強み、向いている職種、転職軸を整理します。  
        強みが分からない人でも、入力例を見ながら進められます。

        ### ③ 求人分析
        気になる求人票を貼り付けて、自分との相性を分析します。  
        求人票スクショにも対応しています。

        ### ④ 職務経歴書作成
        自分の経験と求人票をもとに、職務経歴書の下書きを作成します。  
        Word・PDF・Markdownで保存できます。

        ### ⑤ 面接対策
        想定質問、回答例、STAR法の回答、NG回答例を作成します。

        ### ⑥ 生成履歴
        作成した結果を見返したり、削除したりできます。
        """
    )

    st.divider()

    st.success("まずは左のメニューから「キャリア地図」を開いてください。")

    st.warning(
        """
        注意：
        生成される内容は下書きです。
        応募前には必ず、自分の事実と合っているか確認してください。
        """
    )